const BASE32 = '23456789ABCDEFGHJKMNPQRSTVWXYZ'; // Crockford: no I/L/O/U

/**
 * 64-bit splitmix64 stream over sha256(domainTag + seed). Deterministic:
 * the same identityId always replays the same stream.
 */
function makeRng(seedStr) {
  const digest = createHash('sha256').update(`wa-w1|${seedStr}`).digest();
  let state = digest.readBigUInt64LE(0);
  return {
    u32() {
      state = (state + 0x9e3779b97f4a7c15n) & 0xffffffffffffffffn;
      let z = state;
      z = ((z ^ (z >> 30n)) * 0xbf58476d1ce4e5b9n) & 0xffffffffffffffffn;
      z = ((z ^ (z >> 27n)) * 0x94d049bb133111ebn) & 0xffffffffffffffffn;
      z = z ^ (z >> 31n);
      return Number(z & 0xffffffffn);
    },
    pick(arr) {
      return arr[this.u32() % arr.length];
    },
    /** n-char base32 code (collision space 32^n) */
    code(n) {
      let out = '';
      for (let i = 0; i < n; i++) out += BASE32[this.u32() % BASE32.length];
      return out;
    },
    digits(n) {
      let out = '';
      for (let i = 0; i < n; i++) out += String(this.u32() % 10);
      return out;
    },
    letter() {
      return String.fromCharCode(65 + (this.u32() % 26));
    },
  };
}

/**
 * Generate the fingerprint profile for one identity. DETERMINISTIC: two calls
 * with the same identityId return deep-equal objects — regeneration is
 * idempotent, and the V3 "3× device recreate → same fingerprint" acceptance
 * reduces deterministically to this property.
 *
 * Uniqueness-by-construction: fingerprint / displayId / serial embed
 * base32-code segments (≥32^4, fingerprint ≥32^10) derived from the seed, so
 * pairwise collisions are negligible for any practical fleet AND fully
 * deterministic for a fixed identityId set (the 200-identity test cannot flake).
 */
export function generateFingerprintProfile(identityId) {
  if (typeof identityId !== 'string' || identityId.length < 8 || identityId.length > 64 || !/^[A-Za-z0-9_-]+$/.test(identityId)) {
    throw new Error('generateFingerprintProfile: identityId must be an 8-64 char [A-Za-z0-9_-] string');
  }
  const rng = makeRng(identityId);
  const vendor = rng.pick(POOL_BRANDS);
  const line = rng.pick(POOL_MODEL_LINES);
  const modelNum = `${rng.digits(1)}${rng.code(2)}`; // e.g. "7KQ"
  const model = `${line}${modelNum}`; // no-space form (kernel cmdline carrier forbids spaces), e.g. "Pixel7KQ"
  const slug = `${line.replace(/[^A-Za-z0-9]/g, '').toLowerCase()}-${modelNum.toLowerCase()}`;
  const device = slug.slice(0, 24);
  const productName = slug.slice(0, 24);
  const androidRelease = rng.pick(POOL_ANDROID_RELEASES);
  const securityPatch = `2025-${String(1 + (rng.u32() % 9)).padStart(2, '0')}-${String(1 + (rng.u32() % 28)).padStart(2, '0')}`;
  const buildId = `${rng.letter()}${rng.digits(1)}AB${rng.code(3)}`; // e.g. "B4AB7QF"
  const buildNumber = rng.digits(6);
  const displayCode = rng.code(5); // 32^5 uniqueness for displayId
  const fpCode = rng.code(10).toLowerCase(); // 32^10 uniqueness for fingerprint
  const brandSlug = vendor.brand.toLowerCase();
  // AOSP-style fingerprint (no spaces):
  // brand/device/product:release/buildId/number:type/keys — fpCode rides in
  // the product token so the full string is unique by construction.
  const fingerprint = `${brandSlug}/${device}/${productName}${fpCode}:${androidRelease}/${buildId}/${buildNumber}:userdebug/dev-keys`;
  const displayId = `${androidRelease}.${buildId}.${displayCode}.keys`;
  const serial = `${brandSlug.slice(0, 4).toUpperCase()}-${rng.digits(6)}-${rng.code(4)}`;
  const carrier = rng.pick(POOL_CARRIERS);
  const profile = {
    androidRelease,
    brand: vendor.brand,
    manufacturer: vendor.manufacturer,
    model,
    device,
    productName,
    buildId,
    displayId,
    fingerprint,
    serial,
    locale: rng.pick(POOL_LOCALES),
    timezone: rng.pick(POOL_TIMEZONES),
    carrierName: carrier.name,
    carrierMcc: carrier.mcc,
    carrierMnc: carrier.mnc,
    securityPatch,
  };
  const problems = validateFingerprintProfile(profile);
  if (problems.length) {
    // generator bug — fail closed loudly, never emit a half-valid profile
    throw new Error(`generateFingerprintProfile: internal generator produced invalid profile: ${problems.join('; ')}`);
  }
  return profile;
}

// ---------------------------------------------------------------------------
// Validator (fail-closed)
// ---------------------------------------------------------------------------

/**
 * @returns {string[]} problems (empty = valid). Unknown top-level keys are
 * tolerated ONLY for `securityPatch`; anything else is a shape violation —
 * a silent typo here would silently drop an override on a real device.
 */
export function validateFingerprintProfile(profile) {
  const problems = [];
  if (!profile || typeof profile !== 'object' || Array.isArray(profile)) {
    return ['profile must be a plain object'];
  }
  for (const field of PROFILE_FIELDS) {
    const v = profile[field];
    if (typeof v !== 'string' || v === '') {
      problems.push(`${field} must be a non-empty string`);
      continue;
    }
    const max = FIELD_MAX_LEN[field];
    if (v.length > max) problems.push(`${field} exceeds ${max} chars`);
    if (FIELD_RE[field]) {
      if (!FIELD_RE[field].test(v)) problems.push(`${field} "${v.slice(0, 40)}" does not match expected format`);
    } else if (!SAFE_PROFILE_VALUE_RE.test(v)) {
      problems.push(`${field} "${v.slice(0, 40)}" contains unsafe chars (androidboot/cmdline carrier)`);
    }
  }
  for (const key of Object.keys(profile)) {
    if (!PROFILE_FIELDS.includes(key) && key !== 'securityPatch') {
      problems.push(`unknown profile field "${key}"`);
    }
  }
  // fingerprint must self-consistently reference brand/device (platforms cross-check)
  if (!problems.length) {
    const prefix = `${profile.brand.toLowerCase()}/${profile.device}/`;
    if (!profile.fingerprint.startsWith(prefix)) {
      problems.push('fingerprint must start with "<brand>/<device>/" (AOSP cross-check consistency)');
    }
  }
  return problems;
}

// ---------------------------------------------------------------------------
// Collision checker
// ---------------------------------------------------------------------------

/**
 * Pairwise per-field collision detection over a fleet of profiles.
 * @param {Iterable<{identityId: string, profile: object}>} entries
 * @param {string[]} [fields] fields to check (default: all PROFILE_FIELDS).
 * @returns {{collisions: Array<{field: string, value: string, identityIds: string[], uniqueField: boolean}>, blocking: boolean}}
 *   `blocking` = true iff any collision touches a UNIQUE_PROFILE_FIELD.
 *   Non-unique-field repeats (same model for two identities) are informational
 *   — two real users CAN own the same phone.
 */
export function findProfileCollisions(entries, fields = PROFILE_FIELDS) {
  const list = [...entries];
  const collisions = [];
  for (const field of fields) {
    const buckets = new Map();
    for (const { identityId, profile } of list) {
      const v = profile?.[field];
      if (typeof v !== 'string' || v === '') continue;
      if (!buckets.has(v)) buckets.set(v, []);
      buckets.get(v).push(identityId);
    }
    for (const [value, ids] of buckets) {
      if (ids.length > 1) {
        collisions.push({ field, value, identityIds: ids, uniqueField: UNIQUE_PROFILE_FIELDS.includes(field) });
      }
    }
  }
  return { collisions, blocking: collisions.some((c) => c.uniqueField) };
}

