/**
 * Android property a profile field maps to (the ro.* / persist.* set is the
 * androidboot-cmdline carrier; values reach the device via the generated
 * init mapping, see w1b-image-mapping.js). Array values = one field telling
 * several props the SAME story (hardware). locale/carrier ride
 * settings/telephony — no ro.* carrier for them.
 */
export const PROFILE_PROP_MAP = Object.freeze({
  brand: 'ro.product.brand',
  manufacturer: 'ro.product.manufacturer',
  model: 'ro.product.model',
  device: 'ro.product.device',
  productName: 'ro.product.name',
  buildId: 'ro.build.id',
  displayId: 'ro.build.display.id',
  fingerprint: 'ro.build.fingerprint',
  serial: 'ro.serialno',
  // L2 wave-1 (ADR-031, amended WA-OEMPROP S3): timezone falls to the device —
  // persist.sys.timezone rides the SAME androidboot carrier; the generated rc
  // maps it on the load_persist_props_action trigger (the ordering-guaranteed
  // hook AFTER init reloads stored persistent properties from /data, so a
  // stale /data value can never out-rank the identity story; and BEFORE
  // zygote, so every process resolves the identity timezone).
  timezone: 'persist.sys.timezone',
  // L2 wave-1 (ADR-031, D2): ro.hardware/ro.boot.hardware = "redroid" is a
  // classic container tell. One field, two targets, one story: real devices
  // carry the board name in both (init copies androidboot.hardware=<board>
  // to ro.hardware, and exports the same token as ro.boot.hardware — the
  // very mechanism by which redroid gets "redroid" in both).
  hardware: Object.freeze(['ro.hardware', 'ro.boot.hardware']),
});

/**
 * Flatten PROFILE_PROP_MAP to [field, prop] pairs (array-valued fields
 * expand to one pair per prop). All carrier/mapping/consistency consumers
 * iterate THIS so a field with several props can never be half-wired.
 */
export function profilePropEntries() {
  const out = [];
  for (const [field, prop] of Object.entries(PROFILE_PROP_MAP)) {
    for (const p of Array.isArray(prop) ? prop : [prop]) out.push([field, p]);
  }
  return out;
}

/**
 * Fields that MUST be unique across identities (pairwise collision = the
 * platform-visible clustering signal). Everything else (brand, model,
 * carrier…) MAY legitimately repeat across identities — two real users can
 * own the same phone — so repeats there are recorded but not blocking.
 */
export const UNIQUE_PROFILE_FIELDS = Object.freeze(['fingerprint', 'serial', 'displayId']);

/** All required profile fields (stable order for snapshots/hashing). */
export const PROFILE_FIELDS = Object.freeze([
  'androidRelease', 'brand', 'manufacturer', 'model', 'device', 'productName',
  'buildId', 'displayId', 'fingerprint', 'serial',
  'locale', 'timezone', 'carrierName', 'carrierMcc', 'carrierMnc',
]);

/**
 * Transport-safe value pattern. Values reach the container through docker Cmd
 * array entries `androidboot.<key>=<value>` → kernel cmdline → init. The
 * kernel androidboot parser is stricter than Android itself: ASCII subset, no
 * space, no '=', no quotes/backslash, no control chars. '%' is admitted ONLY
 * for W1b's %20 carrier encoding of spaces in ro.product.model (wa-propctl
 * decodes %20; template validation forbids any other '%' — ADR-028).
 * AOSP build-fingerprint
 * format (`brand/device/product:15/BUILD/NUM:userdebug/keys`) fits.
 */
export const SAFE_PROFILE_VALUE_RE = /^[A-Za-z0-9][A-Za-z0-9._:/,+%-]{0,127}$/;

const FIELD_MAX_LEN = Object.freeze({
  androidRelease: 8,
  brand: 32,
  manufacturer: 32,
  model: 40,
  device: 40,
  productName: 40,
  buildId: 24,
  displayId: 64,
  fingerprint: 128,
  serial: 32,
  locale: 16,
  timezone: 48,
  hardware: 40,
  carrierName: 32,
  carrierMcc: 4,
  carrierMnc: 4,
});

const FIELD_RE = Object.freeze({
  // W1b: real builds ship multi-part releases ("8.0.0") — widen from one dot to two.
  androidRelease: /^\d+(\.\d+){0,2}$/,
  carrierMcc: /^\d{3,4}$/,
  carrierMnc: /^\d{1,4}$/,
  // board names: lowercase alnum with -/_ separators (device codenames on
  // Pixel-class devices, "qcom"/"s5e7880x"-class board ids elsewhere)
  hardware: /^[a-z0-9][a-z0-9_-]{0,39}$/,
});

