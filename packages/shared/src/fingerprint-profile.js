/**
 * Android property a profile field maps to (the ro.* set is the
 * androidboot-cmdline candidate carrier; locale/timezone/carrier ride
 * settings/telephony — V3 decides the per-prop mechanism).
 */
export const PROFILE_PROP_MAP = Object.freeze({
  brand: 'ro.product.brand',
  manufacturer: 'ro.product.manufacturer',
  model: 'ro.product.model',
  device: 'ro.product.device',
  productName: 'ro.product.name',
  buildId: 'ro.build.id',
  displayId: 'ro.build.display.id',
  fingerprint: 'ro.build.fingerprint',
  serial: 'ro.serialno',
});

/**
 * Fields that MUST be unique across identities (pairwise collision = the
 * platform-visible clustering signal). Everything else (brand, model,
 * carrier…) MAY legitimately repeat across identities — two real users can
 * own the same phone — so repeats there are recorded but not blocking.
 */
export const UNIQUE_PROFILE_FIELDS = Object.freeze(['fingerprint', 'serial', 'displayId']);

/** All required profile fields (stable order for snapshots/hashing). */
export const PROFILE_FIELDS = Object.freeze([
  'androidRelease', 'brand', 'manufacturer', 'model', 'device', 'productName',
  'buildId', 'displayId', 'fingerprint', 'serial',
  'locale', 'timezone', 'carrierName', 'carrierMcc', 'carrierMnc',
]);

/**
 * Transport-safe value pattern. Values reach the container through docker Cmd
 * array entries `androidboot.<key>=<value>` → kernel cmdline → init. The
 * kernel androidboot parser is stricter than Android itself: ASCII subset, no
 * space, no '=', no quotes/backslash, no control chars. AOSP build-fingerprint
 * format (`brand/device/product:15/BUILD/NUM:userdebug/keys`) fits.
 */
export const SAFE_PROFILE_VALUE_RE = /^[A-Za-z0-9][A-Za-z0-9._:/+,-]{0,127}$/;

const FIELD_MAX_LEN = Object.freeze({
  androidRelease: 8,
  brand: 32,
  manufacturer: 32,
  model: 40,
  device: 40,
  productName: 40,
  buildId: 24,
  displayId: 64,
  fingerprint: 128,
  serial: 32,
  locale: 16,
  timezone: 48,
  carrierName: 32,
  carrierMcc: 4,
  carrierMnc: 4,
});

const FIELD_RE = Object.freeze({
  androidRelease: /^\d+(\.\d+)?$/,
  carrierMcc: /^\d{3,4}$/,
  carrierMnc: /^\d{1,4}$/,
});

