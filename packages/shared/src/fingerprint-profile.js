/**
 * androidboot key encoding for a dotted Android prop: `ro.build.fingerprint`
 * → `androidboot.oem_ro_build_fingerprint` (→ ro.boot.oem_ro_build_fingerprint
 * on the device). W1b rename: the W1 `wa_` prefix named the farm itself —
 * /proc/cmdline is world-readable, so `wa_*` was a self-branding correlation
 * risk (ADR-028 §naming). `oem_` mimics plausible vendor bootloader variables
 * and carries no water_army signature. Carrier keys stay collision-free vs
 * redroid's own `redroid_*` keys. V3 verifies which of these the runtime
 * actually consumes (w1b image maps them; stock image leaves them inert).
 */
export const CARRIER_KEY_PREFIX = 'androidboot.oem_';

export function propToAndroidbootKey(prop) {
  if (typeof prop !== 'string' || !/^[a-z0-9_.]+$/.test(prop)) {
    throw new Error(`propToAndroidbootKey: invalid prop "${String(prop).slice(0, 60)}"`);
  }
  return `${CARRIER_KEY_PREFIX}${prop.replace(/[.]/g, '_')}`;
}

/**
 * Map a profile onto its Android-prop override set (only fields with a known
 * prop mapping; array-valued map entries expand to one entry per prop).
 * locale/carrier still have no ro.* carrier (settings/telephony side, later
 * phase); timezone rides persist.sys.timezone since L2 wave-1 (ADR-031),
 * hardware rides ro.hardware + ro.boot.hardware.
 */
export function profileToRoOverrides(profile) {
  const out = {};
  for (const [field, prop] of profilePropEntries()) {
    if (typeof profile?.[field] === 'string' && profile[field] !== '') out[prop] = profile[field];
  }
  return out;
}

/**
 * Validate a template-level roOverrides map (JSONB on RedroidTemplate):
 * Android-prop-shaped keys + transport-safe values. Fail closed.
 * @returns {string[]} problems
 */
export function validateRoOverridesMap(map) {
  const problems = [];
  if (!map || typeof map !== 'object' || Array.isArray(map)) return ['roOverrides must be a plain object'];
  const keys = Object.keys(map);
  if (keys.length > 32) problems.push('roOverrides: max 32 props');
  for (const prop of keys) {
    if (!/^(ro|persist)\.[a-z0-9_.]{1,80}$/.test(prop)) {
      problems.push(`roOverrides key "${prop.slice(0, 60)}" must be an ro.*/persist.* prop name`);
      continue;
    }
    const v = map[prop];
    if (typeof v !== 'string' || v === '' || v.length > 128 || !SAFE_PROFILE_VALUE_RE.test(v)) {
      problems.push(`roOverrides["${prop.slice(0, 60)}"] must be a 1-128 char transport-safe string`);
    }
  }
  return problems;
}

/**
 * Merge override layers: base (template static) ← identity profile overrides.
 * Later layers win. Pure; validates the merged result (fail closed).
 * @returns {{overrides: object, problems: string[]}}
 */
export function mergeRoOverrides(layers) {
  const merged = {};
  for (const layer of layers) {
    if (!layer) continue;
    for (const [k, v] of Object.entries(layer)) merged[k] = v;
  }
  return { overrides: merged, problems: validateRoOverridesMap(merged) };
}

/**
 * Build the androidboot Cmd args for a validated override map, in stable
 * (sorted) order so snapshots and mock assertions are deterministic.
 * @throws when the map is invalid (fail closed — never emit partial args)
 */
export function buildRoCmdArgs(map) {
  const problems = validateRoOverridesMap(map);
  if (problems.length) throw new Error(`buildRoCmdArgs: invalid roOverrides: ${problems.join('; ')}`);
  return Object.keys(map)
    .sort()
    .map((prop) => `${propToAndroidbootKey(prop)}=${map[prop]}`);
}
