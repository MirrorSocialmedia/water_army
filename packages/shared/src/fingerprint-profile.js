/**
 * W1 — identity-level device fingerprint profile (ADR-025, 2026-10-26).
 *
 * Problem: every redroid device booted from the same template reports the SAME
 * device fingerprint to target platforms (ro.build.fingerprint / ro.product.*
 * come from the image, not the identity). 200 identities that look like one
 * phone model with one build — and one serial — are trivially clustered.
 *
 * This module is the SINGLE source of truth for the profile shape, the
 * deterministic generator (seed = identityId → regeneration is idempotent),
 * the fail-closed validator (values must survive the androidboot/kernel-cmdline
 * carrier: no spaces, no '=', no quotes, no control chars), and the pairwise
 * collision checker.
 *
 * NOT VERIFIED (V3, ADR-025): whether redroid actually consumes these ro.*
 * overrides on a real device, and which carrier (androidboot.* cmdline vs
 * post-boot setprop) wins per property. Everything here is code + unit-tested
 * logic; real-device behaviour is an explicit open item — never claim it passed.
 *
 * android_id: NOT modelled here on purpose. It is generated by Android on
 * first boot and persists in /data (settings secure), and /data is the
 * per-device persistent dir — it is already identity-stable without us doing
 * anything. Re-inventing it would fight the platform.
 */

import { createHash } from 'node:crypto';

