#!/usr/bin/env bash
# WA-FIXALL S6 image build entry — gms-mtg-oemprop-stealth5 (stealth4-next bundle).
# COPY-only build, pins fail closed, post-build IN-IMAGE asserts (no boot).
# The webview APK is NOT committed (262 MB — gitignored vendor/*.apk);
# vendor/SOURCE-PIN.md records URL + sha256 + fetch date. Fails if the
# vendored APK is missing or drifted from the pin.
# Usage: bash images/gms-mtg-oemprop-stealth5/build.sh [final-tag]
set -euo pipefail
DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$DIR/../.." && pwd)"
FINAL="${1:-water-army/redroid:14.0.0-240527-gms-mtg-oemprop-stealth5}"
BASE_TAG="water-army/redroid:14.0.0-240527-gms-mtg-oemprop-stealth4"
note() { printf '[stealth5-build] %s\n' "$*"; }

BASE_WANT="sha256:92c1922efef6" # stealth4 (WA-FIXALL S2 ship, live image id; S2-RESULTS quotes the manifest digest 8ec65a4d2125)
BASE_GOT="$(docker image inspect -f '{{.Id}}' "$BASE_TAG")"
case "$BASE_GOT" in "$BASE_WANT"*) note "base pin OK: $BASE_TAG @ ${BASE_GOT:0:19}" ;; *) echo "BASE PIN MISMATCH: $BASE_TAG = $BASE_GOT (want ${BASE_WANT}*)" >&2; exit 1 ;; esac

# ---- 0) vendored APK pin ----------------------------------------------------
WV_SHA_WANT="e8d07d54142686ea4452386120961ca32f14c350b9711562c3770cbea577d9ed"
WV_APK="$DIR/vendor/webview-1560807847-arm64.apk"
[ -f "$WV_APK" ] || { echo "missing vendor/webview-1560807847-arm64.apk (see vendor/SOURCE-PIN.md)" >&2; exit 1; }
WV_SHA_GOT="$(sha256sum "$WV_APK" | cut -d' ' -f1)"
[ "$WV_SHA_GOT" = "$WV_SHA_WANT" ] || { echo "WEBVIEW APK DRIFT: $WV_SHA_GOT (want $WV_SHA_WANT)" >&2; exit 1; }
note "apk pin OK: webview ${WV_SHA_GOT:0:12}"

# ---- 1) ro.debuggable decision evidence --------------------------------------
# The extracted base build.prop must carry ro.debuggable=1 (the 1->0 flip was
# tried on-device and KILLED init = exit 129; see build-record.md). The pin
# keeps this honest if the base ever changes shape.
grep -q '^ro.debuggable=1$' "$DIR/vendor/build.prop.orig" || { echo "build.prop.orig: extracted base must carry ro.debuggable=1" >&2; exit 1; }
note "debuggable=1 base pin OK (flip to 0 measured non-viable on redroid)"

# ---- 2) build ---------------------------------------------------------------
# init treats GROUP/OTHER-WRITABLE rc files as "insecure" and silently skips
# the WHOLE file (measured S6: fx2 booted with every carrier row no-op because
# the COPY'd rc landed 0664). Force 0644 on every context file; the post-build
# assert re-checks the merged view.
find "$DIR/files" -type f -exec chmod 0644 {} +
# proc-view source pair lives in images/redroid-w1b/ (generated by the w1b
# tooling, working tree 0664): the .rc must be 0644 (init insecure-file rule),
# the .sh must be 0755 (init execve, no interpreter).
chmod 0644 images/redroid-w1b/oem-proc-view.rc
chmod 0755 images/redroid-w1b/oem-proc-view.sh

docker build -f "$DIR/Dockerfile" -t "$FINAL" "$ROOT"
note "built: $FINAL"

# ---- 3) post-build assertions (no boot) --------------------------------------
docker create --name stealth5-assert "$FINAL" true >/dev/null
TMPW="/tmp/stealth5-wh.$$"
mkdir -p "$TMPW"
trap 'docker rm -f stealth5-assert >/dev/null 2>&1 || true; rm -rf "$TMPW"' EXIT
# R41 swap REVERTED (see Dockerfile header): the in-image webview engine must
# stay the BASE MTG package byte-for-byte, and the base oat dir must still be
# present (its whiteout layer was removed with the revert).
docker cp "stealth5-assert:/system/product/app/webview/webview.apk" /tmp/stealth5-webview.apk
docker create --name stealth5-baseprobe "$BASE_TAG" true >/dev/null
docker cp "stealth5-baseprobe:/system/product/app/webview/webview.apk" /tmp/stealth5-base-webview.apk
cmp -s /tmp/stealth5-webview.apk /tmp/stealth5-base-webview.apk || { echo "ASSERT: in-image webview.apk != BASE apk (R41 revert must be byte-exact)" >&2; exit 1; }
docker cp "stealth5-assert:/system/product/app/webview/oat" /tmp/stealth5-oatprobe >/dev/null 2>&1 || { echo "ASSERT: base webview oat missing in merged view (oat whiteout must NOT be baked while the apk swap is reverted)" >&2; exit 1; }
docker rm -f stealth5-baseprobe >/dev/null 2>&1 || true
for f in /vendor/etc/init/stealth5-extras.rc /vendor/etc/init/oem-ro-map.rc /vendor/etc/init/oem-proc-view.rc; do
  docker cp "stealth5-assert:$f" "/tmp/stealth5-$(basename "$f")" || { echo "ASSERT: missing $f in image" >&2; exit 1; }
  case "$f" in
    /vendor/etc/init/oem-proc-view.rc) SRC="$ROOT/images/redroid-w1b/oem-proc-view.rc" ;;
    *) SRC="$DIR/files${f}" ;;
  esac
  cmp -s "/tmp/stealth5-$(basename "$f")" "$SRC" || { echo "ASSERT: in-image $f != committed file" >&2; exit 1; }
  # init SKIPS "insecure files" (any group/world write bit) and silently drops
  # every trigger in the file — measured on-device S6 v2 (fx2 booted with all
  # carrier rows no-op). rc files must be 0644-owned-by-root in the image.
  MODE="$(stat -c '%a' "/tmp/stealth5-$(basename "$f")")"
  [ "$MODE" = "644" ] || { echo "ASSERT: in-image $f mode $MODE must be 644 (init skips group-writable rc = 'insecure file')" >&2; exit 1; }
done
# proc-view renderer: present + executable (init execve, no interpreter) + bytes.
docker cp "stealth5-assert:/vendor/bin/oem-proc-view.sh" /tmp/stealth5-proc-view.sh || { echo "ASSERT: missing /vendor/bin/oem-proc-view.sh in image" >&2; exit 1; }
cmp -s /tmp/stealth5-proc-view.sh "$ROOT/images/redroid-w1b/oem-proc-view.sh" || { echo "ASSERT: in-image oem-proc-view.sh != committed file" >&2; exit 1; }
MODE="$(stat -c '%a' /tmp/stealth5-proc-view.sh)"
[ "$MODE" = "755" ] || { echo "ASSERT: in-image oem-proc-view.sh mode $MODE must be 755 (init execve)" >&2; exit 1; }
docker cp "stealth5-assert:/vendor/etc/health-fake/battery/health" /tmp/stealth5-psy-health >/dev/null
[ "$(cat /tmp/stealth5-psy-health)" = "Good" ] || { echo "ASSERT: fake psy health file wrong" >&2; exit 1; }
# whiteout effect on the merged view (overlayfs), without booting. The image
# has no usable static exec surface, so the probe is `docker cp` from a
# created container: cp failing with "Could not find the file" = the path is
# whiteouted out of the merged view (and the .wh.su is NOT a literal file).
for gone in /system/xbin/su /system/xbin/.wh.su; do
  docker cp "stealth5-assert:$gone" "$TMPW/whprobe" 2>"$TMPW/whprobe.err" && { echo "ASSERT: $gone still present in merged view (whiteout failed)" >&2; exit 1; }
  grep -q "Could not find the file" "$TMPW/whprobe.err" || { echo "ASSERT: unexpected cp error for $gone: $(cat "$TMPW/whprobe.err")" >&2; exit 1; }
done
docker rm -f stealth5-assert >/dev/null 2>&1 || true
trap - EXIT
note "post-build asserts OK (base webview byte-exact + oat present; rc mode/bytes; psy present; su whiteout effective)"
note "DONE: $FINAL ($(docker image inspect -f '{{.Id}}' "$FINAL"))"
