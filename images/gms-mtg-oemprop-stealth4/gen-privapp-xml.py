#!/usr/bin/env python3
"""WA-FIXALL S2 stealth4 — generate privapp-permissions-stealth4.xml (superset allowlist).
Deterministic: reads committed input lists (sorted perms) next to this script.
Rationale: Android 12+ privileged-permission allowlist enforcement — any
signature|privileged permission requested by the new (2026) GMS/GSF and missing
from the in-image allowlist is silently NOT granted (worst case functional
degradation). We ship the SUPERSET of requested permissions not already granted
by the existing MTG/Google XMLs; extra non-privileged entries are ignored with a
log line (non-fatal), which is the accepted trade (recorded in build-record)."""
import os

DIR = os.path.dirname(os.path.abspath(__file__))
PKGS = [("com.google.android.gms", "perm-gms-new.txt"), ("com.google.android.gsf", "perm-gsf-new.txt")]
OUT = os.path.join(DIR, "files", "vendor", "etc", "permissions", "privapp-permissions-stealth4.xml")

lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- WA-FIXALL S2 stealth4 — GENERATED by gen-privapp-xml.py from perm-{gsf,gms}-new.txt (superset of requested perms not already granted in-image). Do not hand-edit. -->', '<permissions>']
for pkg, fname in PKGS:
    with open(os.path.join(DIR, fname)) as f:
        perms = sorted({ln.strip() for ln in f if ln.strip()})
    lines.append(f'    <!-- {pkg}: {len(perms)} entries -->')
    lines.append(f'    <privapp-permissions package="{pkg}">')
    for p in perms:
        lines.append(f'        <permission name="{p}" />')
    lines.append('    </privapp-permissions>')
lines.append('</permissions>')
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", OUT, len(lines), "lines")
